"""Rewrite the tool list in README.md from the tool definitions.

The block between the markers below is generated; edit the tools, not the
block. Reads the source with ast, so it needs neither FreeCAD nor Agent Link.

    python3 tools/gen_readme_tools.py          # rewrite README.md
    python3 tools/gen_readme_tools.py --check  # exit 1 if it is out of date
"""
import ast
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = "<!-- tools:begin (generated by tools/gen_readme_tools.py) -->"
END = "<!-- tools:end -->"
# (source file, group shown; None: the file's own GROUP)
SOURCES = [("safetynet/fam_history.py", None), ("safetynet/fam_safety.py", None)]


def _const(node):
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def _short(desc, limit=110):
    """The first sentence, without its argument details."""
    s = desc
    for _ in range(3):
        s = re.sub(r"\s*\([^()]*\)", "", s)
        s = re.sub(r"\s*\{[^{}]*\}", "", s)
    s = re.split(r"(?<=[.!?])\s|\s—\s|:\s|\s\|\s", s.strip(), maxsplit=1)[0].strip().rstrip(".;,")
    if len(s) > limit:
        s = s[:limit].rsplit(" ", 1)[0].rstrip(",;") + " …"
    return s.replace("|", "\\|") + "."


def read(path):
    tree = ast.parse(open(os.path.join(ROOT, path), encoding="utf-8").read())
    group = None
    for n in tree.body:
        if isinstance(n, ast.Assign) and any(getattr(t, "id", None) == "GROUP" for t in n.targets):
            group = _const(n.value)
    found = []
    for n in ast.walk(tree):
        if isinstance(n, ast.Call) and getattr(n.func, "id", getattr(n.func, "attr", None)) == "Tool" and len(n.args) >= 2:
            name, desc = _const(n.args[0]), _const(n.args[1])
            if name:
                found.append((n.lineno, name, desc or ""))
    return group, [(name, desc) for _, name, desc in sorted(found)]


def block():
    rows = ["| Tool | Group | What it does |", "|---|---|---|"]
    for path, label in SOURCES:
        group, tools = read(path)
        for name, desc in tools:
            rows.append(f"| `{name}` | {label or group or ''} | {_short(desc)} |")
    return "\n".join([BEGIN, *rows, END])


def render(text):
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        raise SystemExit("README.md has no tools block (markers missing)")
    return text[:i] + block() + text[j + len(END):]


def main(argv):
    readme = os.path.join(ROOT, "README.md")
    old = open(readme, encoding="utf-8").read()
    new = render(old)
    if "--check" in argv:
        if new != old:
            print("README.md tool list is out of date: run python3 tools/gen_readme_tools.py")
            return 1
        return 0
    if new != old:
        open(readme, "w", encoding="utf-8").write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
